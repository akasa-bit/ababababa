// 帆に光の運ぶエネルギーが移る割合を、止まった状態から速さ beta までの加速で通したもの。
// その瞬間の割合 2β/(1+β) (完全な反射の帆) を、運動量の式で積分した: 必要な光 = mc² (γβ + γ − 1) / 2
const sailEff = (beta) => { const g = 1 / Math.sqrt(1 - beta * beta); return (2 * (g - 1)) / (g * beta + g - 1); };
// 1 便の推進のエネルギー [J]。m = 積み荷と船の質量 [kg]、mode = 'route' (両端のレーザー) / 'free' (減速は磁気帆と反物質)。
// acc = 出発する側のレーザーの電気、dec = 'route' なら着く側のレーザーの電気、'free' なら出発する側で作って積む反物質の電気
function propulsion(m, beta, mode) {
  const g = 1 / Math.sqrt(1 - beta * beta);
  const chain = PROP.laser * PROP.beam * sailEff(beta);
  if (mode === 'route') {
    const e = ((g - 1) * m * C2) / chain;
    // 着く側のレーザーで止めるとき、帆はレーザーへ近づくので、跳ね返る光が青くずれて船の運動エネルギーを持ち去る。要る光は mc² (γβ − γ + 1) / 2 で、
    // 加速 (γβ + γ − 1) の 0.16 倍 (0.95c)。加速を時間反転したもの (シミュレーション版だけ。ゲーム版は加速と同じ量のまま)
    const d = SIM_ONLY ? (m * C2 * (g * beta - g + 1)) / 2 / (PROP.laser * PROP.beam) : e;
    return { acc: e, dec: d, mass: m, anti: 0 };
  }
  // 反物質ロケット: 速さの変化 (ラピディティ) atanh(βf) = 排気速度 × ln(質量比)。推進剤の半分が反物質
  const R = GM.exp(GM.atanh(PROP.magsailTo) / PROP.amExhaust);
  const anti = (m * (R - 1)) / 2;
  return { acc: ((g - 1) * m * R * C2) / chain, dec: (anti * C2) / PROP.amEff, mass: m * R, anti };
}
